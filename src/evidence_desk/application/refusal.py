"""判断一段回答是不是「拒答」。

## 为什么单独一个文件

这个判断**生产和评测都要用**，而且必须用同一份逻辑：

- 生产：决定 API 返回的 ``answered`` 字段、决定要不要附引用
- 评测：算 Refusal Accuracy

两边各写一份的话，迟早出现「评测说拒答了、生产说没拒答」的分裂——
指标是对的，线上行为是错的，而且不报错。

放在 application 层而不是 evaluation 层，是因为分层规矩：
**评测可以依赖生产代码，生产不能反过来依赖评测代码。**

## 这里是四层拒答策略里的第 2 层（兜底）

完整策略：

    第0层 前置闸门：检索 Top-1 分数太低 → 直接拒答，连模型都不调
                    （最可靠，因为分数是检索器算的客观数字，不依赖模型行为。
                     阈值必须按真实分数分布标定，见 config.answer_min_score
                     的注释——照搬别处的阈值会把该答的题大批误拒）
    第1层 显式声明：让模型返回结构化字段 can_answer —— **本版未实现**，
                    要改整个输出格式，记在 ADR 的改进方向里
    第2层 文本兜底：就是本文件 —— 从回答文本里认出拒答意图
    第3层 后置校验：声称回答了却一个引用标号都没有 → 打标记，不改判

**本文件是兜底，不该是主判断。** 现在因为第 1 层没做，它暂时承担了主判断，
这是已知的架构债，不是设计意图。
"""

import re

# 判「这段话是不是在拒答」的模式。在**去掉空白和标点之后**的文本上匹配，
# 所以模式里不写标点。
#
# 为什么不能只用 `NO_EVIDENCE_REPLY not in text` 那种精确匹配：那是一字不差的
# 比对，模型少个句号、换个说法（「抱歉，知识库里没有这方面的资料」）就会被判成
# 「正经回答了」。更根本的问题是——那等于**把程序的状态判断交给一段自然语言**，
# 而措辞由模型决定、不受你控制。换模型、调温度、升级 API 都可能让它失效，
# 而且不报错，只会让指标莫名其妙地飘。
_REFUSAL_PATTERNS = [
    # 「知识库（里/中）没有……信息/资料/内容」。
    # 刻意**不要求**出现「相关」「对应」这类修饰词——模型很可能写成
    # 「知识库里没有这方面的资料」，卡死修饰词会漏掉一大批变体。
    # 这条是写这套模式时踩到的坑：第一版要求了「相关|对应」，被自己的测试抓出来。
    re.compile(
        r"(知识库|参考资料|文档).{0,10}(没有|未|不包含).{0,10}(信息|资料|内容|文档|记载)"
    ),
    re.compile(r"无法回答"),
    re.compile(
        r"(没有|未).{0,4}(找到|检索到).{0,8}(相关|对应).{0,4}(资料|信息|内容|文档)"
    ),
    re.compile(r"(参考)?资料.{0,4}(不足|不够)"),
    re.compile(r"抱歉.{0,14}(无法|不能|没有).{0,10}(回答|提供|找到|资料|信息)"),
]

# 拒答话术都很短。超过这个长度还想判成拒答，多半是一段正经回答里恰好出现了
# 「无法回答」之类的字眼（比如在讲"什么情况下无法回答某类请求"），不能算拒答。
# 这是防误伤的兜底。
_MAX_REFUSAL_LENGTH = 120

_PUNCTUATION = re.compile(r"[\s、，,。.！!？?：:；;「」『』\"'“”‘’（）()\[\]【】]+")


def detect_refusal(text: str) -> bool:
    """判断一段回答是不是在拒答。返回 True 表示这是一次拒答。

    三层容错，各解决一个问题：
    1. 去掉空白和标点再匹配 —— 句号、逗号写不写都不影响判断；
    2. 用一组「拒答意图」模式而不是死盯一句固定话术 —— 模型换说法也认得出；
    3. 长度兜底 —— 防止正经回答里偶然出现拒答字眼被误伤。
    """

    normalized = _PUNCTUATION.sub("", text)
    if not normalized or len(normalized) > _MAX_REFUSAL_LENGTH:
        return False
    return any(pattern.search(normalized) for pattern in _REFUSAL_PATTERNS)
